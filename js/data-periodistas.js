function bucketPeriodistas(anio){
  const keys=Object.keys(PERIODISTAS_POR_ERA).map(Number).sort((a,b)=>a-b);
  let pick=keys[0];
  keys.forEach(k=>{ if(k<=anio) pick=k; });
  return PERIODISTAS_POR_ERA[pick]||PERIODISTAS_POR_ERA[keys[keys.length-1]];
}

