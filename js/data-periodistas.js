function slugPeriodista(n){
  return String(n||"").normalize("NFD").replace(/[\u0300-\u036f]/g,"").replace(/\([^)]*\)/g,"").toLowerCase().replace(/[^a-z0-9]+/g,"-").replace(/^-|-$/g,"");
}
function fotoPeriodista(n){
  if(typeof PERIODISTAS_FOTOS==="undefined") return null;
  return PERIODISTAS_FOTOS[slugPeriodista(n)]||null;
}

